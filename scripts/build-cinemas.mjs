#!/usr/bin/env node
/**
 * data/indian_cinema_database.csv  (+ optional data/cinema-coordinates.csv, data/city-centers.json)
 *   -> src/data/cinemas.generated.ts
 * Run:  npm run data:build      (also runs automatically before `npm run build`)
 * Edit the CSV in Excel/Sheets, run this, commit both files. Fails loudly on bad data.
 */
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { parseCsv } from './lib/csv.mjs'
import { buildCinemas } from './lib/build.mjs'

const rows = parseCsv(readFileSync('data/indian_cinema_database.csv','utf8'))
const centers = JSON.parse(readFileSync('data/city-centers.json','utf8'))
const coords = existsSync('data/cinema-coordinates.csv') ? parseCsv(readFileSync('data/cinema-coordinates.csv','utf8')) : []
const { cinemas, centers:cityList, errors, warnings } = buildCinemas(rows, centers, coords)
warnings.forEach(w=>console.warn('warning:', w))
if (errors.length){ errors.forEach(e=>console.error('ERROR:', e)); process.exit(1) }
const exactN = cinemas.filter(c=>c.precision==='exact').length
const out = `// AUTO-GENERATED by scripts/build-cinemas.mjs from data/indian_cinema_database.csv — do not edit by hand.
export type RawCinema = { id:string; name:string; chain:string; venueType:string; area:string; address:string; pin:string; city:string; district:string; state:string; screens:number|null; lat:number; lng:number; precision:'exact'|'city'; formats:string[]|null }
export type CityCenter = { name:string; state:string; lat:number; lng:number; count:number }
export const RAW_CINEMAS: RawCinema[] = ${JSON.stringify(cinemas)}
export const CITY_CENTERS: CityCenter[] = ${JSON.stringify(cityList)}
`
writeFileSync('src/data/cinemas.generated.ts', out)
console.log(`OK: ${cinemas.length} cinemas, ${cityList.length} cities, ${new Set(cinemas.map(c=>c.state)).size} states; exact coordinates: ${exactN}, city-centre only: ${cinemas.length-exactN}`)
